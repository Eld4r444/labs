a = 15
b = 4

print("Сумма:", a + b)
print("Разность:", a - b)
print("Произведение:", a * b)
print("Обычное деление:", a / b)
print("Целочисленное деление:", a // b)
print("Остаток от деления:", a % b)
print("Возведение в степень:", a ** b)

# / возвращает float с дробной частью (3.75),
# // отбрасывает дробную часть и возвращает целую часть (3)

print("2 + 3 * 4 =", 2 + 3 * 4)
print("(2 + 3) * 4 =", (2 + 3) * 4)
